package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"text/template"

	"minikitex/idl"
)

type genData struct {
	Package string
	*idl.Spec
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintf(os.Stderr, "usage: gen <idl> <out.go>\n")
		os.Exit(2)
	}
	spec, err := idl.ParseFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	pkg := filepath.Base(filepath.Dir(os.Args[2]))
	if pkg == "" || pkg == "." {
		fmt.Fprintf(os.Stderr, "gen: output must be in a package dir, e.g. gen/order/order.go\n")
		os.Exit(2)
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, &genData{Package: pkg, Spec: spec}); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.MkdirAll(filepath.Dir(os.Args[2]), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(os.Args[2], src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

